/** Build an AiInsight shell around a plain-text answer from the Catalyst Function. */
function textInsight(answer: string, source: AiInsight["explain"]["source"], meta: AiResponseMeta = {}): AiInsight {
  const cloudScaleFallback = /Cloud Scale Retrieval/i.test(meta.model || "");
  const conversational = meta.response_kind === "conversation" || meta.response_kind === "clarification" || source === "conversation";
  return {
    answer,
    analysis: meta.analysis,
    source_chart: meta.source_chart,
    explain: {
      confidence: null,
      response_kind: meta.response_kind,
      response_scope: meta.response_scope,
      reasoning: conversational ? "Conversational response; no case records were searched or used."
        : cloudScaleFallback
        ? "NETRA returned a bounded response from Catalyst Cloud Scale after applying retrieval and grounding checks."
        : source === "llm" ? "Generated by Zoho Catalyst QuickML." : "AI backend not connected in this build.",
      records_used: 0,
      evidence: [],
      alternatives: [],
      source: conversational ? "conversation" : cloudScaleFallback ? "lookup" : source,
      audit_id: meta.audit_id || `A-${Date.now().toString(36).toUpperCase()}`,
      processing_ms: meta.processing_ms || 0,
      ai_model: meta.model || (source === "llm" ? "VL-Qwen3.6-35B-A3B" : "none"),
    },
  };
}

/** Build an AiInsight from a RAG answer + the case documents it was grounded on. */
function ragInsight(answer: string, sources: RagSource[], meta: AiResponseMeta = {}): AiInsight {
  if (meta.source_chart) {
    const result = textInsight(answer, 'lookup', meta);
    result.sources = sources;
    result.explain.records_used = sources.length;
    result.explain.reasoning = meta.response_scope === 'supplied'
      ? 'Chart values were copied from the officer’s supplied figures. They are not verified Cloud Scale statistics.'
      : 'Chart values were copied from stored document text. The table retains each value and its source excerpt.';
    return result;
  }
  if (meta.response_scope === 'documents') {
    const result = textInsight(answer, 'rag', meta);
    result.sources = sources;
    result.explain.records_used = sources.length;
    result.explain.reasoning = /Evidence Q&A|Source Retrieval/.test(meta.model || '')
      ? 'Answered from stored photo observations and any explicitly linked synthetic profile records. An exact demo-file match is not biometric identification.'
      : 'Answered from the attached library files. Citations identify numbered OCR passages or generated-report text, not verified crime-database records.';
    result.explain.evidence = sources.map(source => source.title);
    return result;
  }
  if (meta.analysis) {
    const result = textInsight(answer, 'lookup', meta);
    result.sources = sources;
    result.explain.records_used = meta.analysis.total;
    result.explain.reasoning = `Calculated from the current KSP records. ${meta.analysis.scope}. Retrieved ${meta.analysis.generated_at}. Full FIR references are included with the analysis.`;
    result.explain.evidence = sources.map(source => source.title || '').filter(Boolean);
    return result;
  }
  if (meta.response_kind === "conversation" || meta.response_kind === "clarification") {
    return textInsight(answer, "conversation", meta);
  }
  const cloudScaleFallback = /Cloud Scale Retrieval/i.test(meta.model || "");
  const evidence = sources
    .map((s) => (s.title || s.snippet || "").toString().slice(0, 80))
    .filter(Boolean)
    .slice(0, 8);
  return {
    answer,
    // Keep the rich source structure (title/snippet/score) for the Sources panel.
    sources: sources.slice(0, 8).map((s) => ({
      title: (s.title || "").toString(),
      snippet: (s.snippet || "").toString(),
      score: typeof s.score === "number" ? s.score : null,
    })),
    explain: {
      confidence: null,
      response_kind: meta.response_kind,
      reasoning: !sources.length ? "No matching source records were returned. This is not a verified case finding."
        : cloudScaleFallback
        ? "NETRA answered from the cited Catalyst Cloud Scale records after applying retrieval and grounding checks."
        : sources.length
        ? `Grounded in ${sources.length} case document${sources.length === 1 ? "" : "s"} retrieved from the knowledge base by Zoho Catalyst QuickML RAG.`
        : "Answered by Zoho Catalyst QuickML RAG (no source passages returned).",
      records_used: sources.length,
      evidence,
      alternatives: [],
      source: cloudScaleFallback ? "lookup" : "rag",
      audit_id: meta.audit_id || `A-${Date.now().toString(36).toUpperCase()}`,
      processing_ms: meta.processing_ms || 0,
      ai_model: meta.model || "QuickML RAG",
    },
  };
}

function value(row: Record<string, unknown>, ...keys: string[]): string {
  for (const key of keys) {
    const raw = row[key];
    if (raw != null && String(raw).trim()) return String(raw);
  }
  return "";
}

function searchInsight(query: string, hits: Array<{ table: string; row: Record<string, unknown> }>, warning?: string | null, meta: AiResponseMeta = {}): AiInsight {
  const lines = hits.slice(0, 6).map((hit, index) => {
    const row = hit.row;
    const primary = value(row, "fir_number", "case_number", "name", "full_name", "vehicle_number", "record_id", "ROWID") || "record";
    const detail = [
      value(row, "crime_type", "offence_type", "status"),
      value(row, "district", "station_name", "location"),
      value(row, "description", "summary", "notes").slice(0, 110),
    ].filter(Boolean).join(" · ");
    return `${index + 1}. ${hit.table}: ${primary}${detail ? ` — ${detail}` : ""}`;
  });
  const topValues = (keys: string[]) => {
    const counts = new Map<string, number>();
    for (const hit of hits) {
      const item = value(hit.row, ...keys);
      if (item) counts.set(item, (counts.get(item) || 0) + 1);
    }
    return [...counts.entries()]
      .sort((a, b) => b[1] - a[1])
      .slice(0, 3)
      .map(([item, count]) => `${item} (${count})`)
      .join(", ");
  };
  const wantsBrief = /(short|brief|concise|quick).{0,24}(summary|description|overview)|\b(summarise|summarize|summary|overview|describe|description)\b|ಸಂಕ್ಷಿಪ್ತ|ಸಾರಾಂಶ/i.test(query);
  const offences = topValues(["crime_type", "offence_type", "type"]);
  const districts = topValues(["district", "station_name", "location"]);
  const references = hits
    .map((hit) => value(hit.row, "fir_number", "case_number", "name", "ROWID"))
    .filter(Boolean)
    .slice(0, 3)
    .join(", ");
  const answer = wantsBrief
    ? `NETRA reviewed ${hits.length} relevant Cloud Scale record${hits.length === 1 ? "" : "s"}. ` +
      `${offences ? `The leading offence pattern is ${offences}. ` : ""}` +
      `${districts ? `The strongest location signal is ${districts}. ` : ""}` +
      `${references ? `Representative records: ${references}. ` : ""}` +
      "Verify the cited records before operational action."
    : `I found ${hits.length} relevant Cloud Scale record${hits.length === 1 ? "" : "s"}:\n\n${lines.join("\n")}`;
  return {
    answer,
    explain: {
      confidence: null,
      reasoning: `QuickML RAG/chat did not return a usable answer, so NETRA answered from bounded Catalyst Cloud Scale search results.${warning ? ` ${warning}` : ""}`,
      records_used: hits.length,
      evidence: hits.slice(0, 8).map((hit) => `${hit.table} · ${value(hit.row, "fir_number", "case_number", "name", "ROWID") || "record"}`),
      alternatives: [],
      source: "lookup",
      audit_id: meta.audit_id || `A-${Date.now().toString(36).toUpperCase()}`,
      processing_ms: meta.processing_ms || 0,
      ai_model: meta.model || "Catalyst Cloud Scale Search",
    },
  };
}

function contextualFallbackQuery(query: string, history: ConversationMessage[]): string {
  const followUp = /(\bthere\b|\bthose\b|\bthem\b|\bthese\b|\bit\b|\bthat\b|\bsame\b|what about|how about|tell me more|more details|\balso\b)|^(summarise|summarize|summary|overview|describe|description|ಸಂಕ್ಷಿಪ್ತ|ಸಾರಾಂಶ)$/i.test(query);
  if (!followUp) return query;
  const previous = [...history].reverse().find((message) => message.role === "user" && routeConversation(message.content).kind === "records");
  return previous ? `${query}\nPrevious officer request: ${previous.content.slice(0, 500)}` : query;
}

