import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { documentChart, numericSeries, suppliedChart } = require('../functions/ai_quickml/source-chart');
const { conversationAttachments } = require('../functions/ai_quickml/assistant-report');
const file = { id: 'document-test', filename: 'District report.pdf', text: '| District | FIRs |\n| --- | --- |\n| Mysuru | 42 |\n| Udupi | 48 |\n| Total | 90 |' };
const make = (text, query = 'Show a visual representation of this report statistics') => documentChart({ query }, [{ ...file, text }]);
const response = make(file.text);
assert.equal(response.response_scope, 'documents');
assert.deepEqual(response.source_chart.rows.map(row => [row.label, row.value]), [['Mysuru', 42], ['Udupi', 48]]);
assert(response.sources.every(source => file.text.includes(source.snippet)));
assert.equal(make(file.text, 'Show a pie chart').source_chart.kind, 'pie');
assert.equal(make(file.text, 'Show a line chart').source_chart.kind, 'line');
assert.equal(make('Mysuru: 42\nUdupi: 48').source_chart.rows[1].value, 48);
assert.equal(make('District | Current | FIRs | Cases\nMysuru | 10 | 42 | 48').response_kind, 'clarification');
assert.equal(make('There are many crimes, but no figures are provided.').response_kind, 'clarification');
assert.equal(make('FIR number: 104060011202600001\nAge: 42').response_kind, 'clarification');
assert.equal(make('Mysuru: 42\nMysuru: 48').response_kind, 'clarification');
assert.equal(make('Mysuru: -4\nUdupi: 2', 'Show a pie chart').response_kind, 'clarification');
assert.equal(documentChart({ query: 'hello' }, [file]), null);
const html = conversationAttachments({ source_chart: response.source_chart, sources: response.sources });
assert(html.includes('<svg') && html.includes('42') && html.includes('48') && html.includes('District report.pdf'));
const malicious = { ...response.source_chart, title: '<script>bad</script>', rows: [{ label: '<img onerror=alert(1)>', value: 4, quote: 'an unsafe string' }] };
assert(!conversationAttachments({ source_chart: malicious }).includes('<script>'));
assert(numericSeries(file.text).length === 1);
const multi = 'District | FIRs | Cases\nMysuru | 42 | 30\nUdupi | 48 | 38';
assert.equal(make(multi).response_kind, 'clarification', 'multiple measures must not be guessed');
assert.deepEqual(make(multi, 'Chart FIRs by district').source_chart.rows.map(row => row.value), [42, 48]);
assert.deepEqual(make(multi, 'Chart cases by district').source_chart.rows.map(row => row.value), [30, 38]);
const pasted = 'Draw a bar chart of these supplied figures:\nMysuru: 42\nUdupi: 48';
assert.deepEqual(suppliedChart({ query: pasted }).source_chart.rows.map(row => row.value), [42, 48]);
assert.equal(suppliedChart({ query: pasted }).response_scope, 'supplied');
assert.match(suppliedChart({ query: pasted }).source_chart.warning, /not verified/);
assert.equal(suppliedChart({ query: 'Show these as a pie chart', history: [{ role: 'user', content: pasted }] }).source_chart.kind, 'pie');
assert.equal(suppliedChart({ query: 'Now show the same as a line chart', history: [{ role: 'user', content: pasted }, { role: 'user', content: 'Show these as a pie chart' }] }).source_chart.kind, 'line');
assert.equal(suppliedChart({ query: 'Show these as a chart', history: [{ role: 'assistant', content: 'Mysuru: 999\nUdupi: 999' }] }), null, 'model prose must not supply figures');
assert.equal(suppliedChart({ query: 'Show these as a chart', history: [{ role: 'user', content: pasted }, { role: 'user', content: 'What is machine learning?' }] }), null, 'changed topic must not resurrect older figures');
assert.equal(suppliedChart({ query: 'Draw a chart\nFIR number: 104060011202600001\nAge: 42' }), null);
console.log('Report charts: deterministic values, source excerpts, ambiguity/no-data checks, pie/line/bar exports and escaping passed.');
